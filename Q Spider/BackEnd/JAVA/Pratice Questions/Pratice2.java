// Print the reverse the Number 5 to 1 using all loops .

//for
class  Pratic2
{
	public static void main(String[] args) 
	{
		
		for (int i = 5 ; i >= 1 ; i-- )
			
		{
			System.out.println(i);
		}
		
	}
}



//While
class  Pratic2
{
	public static void main(String[] args) 
	{
		
		int i = 5;
		
		while (i>=1)
		{
			System.out.println(i);
			i--;
		}
		
	}
}


